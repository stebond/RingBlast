"""Saves screenshots of every tab of the GUI for the publication (python tools/make_screenshots.py).

Runs without a display (Qt offscreen), with a throw-away user folder so that personal settings and
edited databases never appear in the pictures.  Output: figures/screenshots/NN_<tab>.png

Options:
  --photo FILE [--scale-length-cm L --scale-px X1,Y1,X2,Y2]   use a real muck-pile photo
  --size WxH      window size in pixels (default 1500x950)
  --zoom F        pixel ratio, 2 gives print quality (default 2)
  --out DIR       output folder (default figures/screenshots)
Without --photo a synthetic photo with known fragment sizes is used.
"""
import argparse
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--photo")
    ap.add_argument("--scale-px", help="x1,y1,x2,y2 of the reference length in the photo")
    ap.add_argument("--scale-length-cm", type=float, default=60.0)
    ap.add_argument("--size", default="1500x950")
    ap.add_argument("--zoom", type=float, default=2.0)
    ap.add_argument("--out", default=str(ROOT / "figures" / "screenshots"))
    a = ap.parse_args()

    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    os.environ["QT_SCALE_FACTOR"] = str(a.zoom)
    from PySide6 import QtWidgets as W
    from ringblast import db, plotstyle

    tmp = Path(tempfile.mkdtemp(prefix="ringblast_shots_"))
    db.USER_DIR = tmp
    plotstyle.STYLE_FILE = tmp / "plot_style.json"
    plotstyle.set_style(plotstyle.PlotStyle())

    from ringblast.gui.app import MainWindow
    app = W.QApplication.instance() or W.QApplication([])
    win = MainWindow()
    width, height = (int(v) for v in a.size.lower().split("x"))
    win.resize(width, height)
    win.show()

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    count = [0]

    def shot(name: str, widget=None):
        app.processEvents()
        count[0] += 1
        f = out / f"{count[0]:02d}_{name}.png"
        (widget or win).grab().save(str(f))
        print("saved", f)

    win.proj_name.setText("Example stope")
    win.proj_notes.setPlainText("Screenshots generated by tools/make_screenshots.py")
    win.w["n_sub"].setValue(3)
    win.w["arch"].setValue(4.0)                 # arched roof, to show the option
    app.processEvents()

    win.tabs.setCurrentIndex(0); shot("stope_layout")
    win.run()
    win.tabs.setCurrentIndex(1)
    for i in range(win.plots.count()):
        win.plots.setCurrentIndex(i)
        shot(f"blast_design_{win.plots.tabText(i).lower().replace(' ', '_')}")

    win.tabs.setCurrentIndex(2); win.rock_tab.table.selectRow(0); shot("rock_properties")
    win.tabs.setCurrentIndex(3); win.expl_tab.table.selectRow(0); shot("explosives")

    # ------------------------------------------------------------ muck-pile photos
    import cv2
    from ringblast import imageanalysis as ia
    tab = win.images_tab
    if a.photo:
        photo = Path(a.photo)
        px = [float(v) for v in a.scale_px.split(",")] if a.scale_px else None
    else:
        from synth import SCALE, make_photo
        img, _ = make_photo()
        photo = tmp / "synthetic_muck_pile.png"
        cv2.imwrite(str(photo), img)
        px = [100, 100, 100 + 60 * SCALE, 100]
    tab.add_files([str(photo)])
    tab.location.setPlainText("Example level, ring 7, left side of the pile")
    tab.notes.setPlainText("Photo used to illustrate the analysis")
    win.tabs.setCurrentIndex(4)
    if px:
        tab.set_scale_points((px[0], px[1]), (px[2], px[3]), a.scale_length_cm)
    else:
        print("no --scale-px given: the photo is not analysed")
    shot("photos_original_with_scale")
    if px:
        win.run()
        tab.analyse(tab.records, quiet=True)
        tab.view_mode.setCurrentIndex(0); shot("photos_fragments")
        tab.left_tabs.setCurrentIndex(1)
        tab.view_mode.setCurrentIndex(3); shot("photos_segmentation_mask")
        tab.view_mode.setCurrentIndex(2); shot("photos_segmentation_preprocessed")
        tab.view_mode.setCurrentIndex(0)
        tab.refresh(); shot("photos_distribution")

    win.tabs.setCurrentIndex(5); shot("settings")
    from ringblast.gui.help import AboutDialog
    about = AboutDialog(win, win.windowIcon()); about.show(); shot("about_dialog", about); about.close()
    print(f"{count[0]} screenshots in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
